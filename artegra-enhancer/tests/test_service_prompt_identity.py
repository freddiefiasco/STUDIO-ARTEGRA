def make_input(folder: Path) -> Path:
    folder.mkdir(parents=True, exist_ok=True)
    y, x = np.mgrid[0:240, 0:320]
    pic = np.stack([(x * 255 // 319), (y * 255 // 239), ((x // 16 + y // 16) % 2) * 160 + 40], -1).astype(np.uint8)
    path = folder / "identity.png"
    Image.fromarray(pic).save(path)
    return path


def normalise(text: str, job: str, roots) -> str:
    text = text.replace(job, "<job>")
    for name, root in roots:
        for form in {str(root), str(root).replace("\\", "/"), json.dumps(str(root))[1:-1]}:
            text = text.replace(form, name)
    return re.sub(r"\bj[0-9a-f]{12}\b", "<job>", text)


def canonical(path: Path, job: str, roots) -> str:
    graph = json.loads(normalise(path.read_text(encoding="utf8"), job, roots))
    return hashlib.sha256(json.dumps(graph, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def run_group(service_factory, work: Path, group, picture: Path) -> dict:
    """{case id: [stage hashes]} for one group, with a service from service_factory(state, env, settings)."""
    state = work / group["id"]
    svc = service_factory(state, dict(COMMON_ENV, **group["env"]), {})
    try:
        if group["extra"]:
            code, body, _ = svc.post("/api/settings", group["extra"])
            assert code == 200, body
        code, res, _ = svc.post("/api/inputs", {"paths": [str(picture)]})
        assert code == 200 and res["items"], res
        media = res["items"][0]["id"]
        jobs = {}
        for n, case in enumerate(group["cases"]):
            body = {"client_request_id": f"{n:032x}", "media_ids": [media], "settings": case["settings"]}
            code, job, _ = svc.post("/api/jobs", body)
            assert code == 201, (case["id"], job)
            jobs[case["id"]] = job
            if group.get("one_at_a_time"):
                svc.wait_job(job["id"], lambda j: j["state"] in ("done", "failed", "cancelled"), timeout=120)
        out = {}
        for case in group["cases"]:
            job = svc.wait_job(jobs[case["id"]]["id"], lambda j: j["state"] in ("done", "failed", "cancelled"), timeout=240)
            item = job["items"][0]
            assert item["state"] == "done", (case["id"], json.dumps(job)[:1500])
            files = sorted((state / "workers").glob(f"*/fake-prompts/cu_{job['id']}_{item['id']}_s*.json"),
                           key=lambda p: p.name)
            assert files, case["id"]
            roots = [("<state>", state), ("<input>", picture.parent)]
            out[case["id"]] = {"stages": [canonical(p, job["id"], roots) for p in files],
                               "workers": sorted({p.parents[1].name for p in files}),
                               "mode": (item.get("run") or {}).get("mode"), "cards": (item.get("run") or {}).get("cards")}
        return out
    finally:
        svc.kill()


def run_all(service_factory, work: Path, beta_only=True) -> dict:
    picture = make_input(work / "input")
    results = {}
    for group in GROUPS:
        if group.get("beta_only") and not beta_only:
            continue
        results.update(run_group(service_factory, work, group, picture))
    return results


def test_the_prompts_equal_the_final_v5s(tmp_path):
    from tests.service.helpers import ServiceProcess

    def factory(state, env, settings):
        return ServiceProcess(state, env=env, settings=settings, output_dir=state.parent / ("out-" + state.name)).start()

    fixture = json.loads(FIXTURE.read_text(encoding="utf8"))
    started = time.monotonic()
    got = run_all(factory, tmp_path)
    assert sorted(got) == sorted(fixture["cases"])
    differ = []
    for case_id, want in fixture["cases"].items():
        reference = want["beta"] if want.get("beta_only") else want["final"]
        if got[case_id]["stages"] != reference["stages"] or got[case_id]["workers"] != reference["workers"]:
            differ.append((case_id, got[case_id], reference))
    assert differ == [], json.dumps(differ, indent=1)[:4000]
    # The two-card Bolt image shared both cards with the proven recipe, as the final v5's did.
    assert got["shared-bolt-default-2x"]["workers"] == ["gpu0+1"] and got["shared-bolt-default-2x"]["cards"] == [0, 1]
    assert got["bolt-default-2x"]["mode"] == "fast"
    assert time.monotonic() - started < 600
